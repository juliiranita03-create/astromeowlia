let lyricsInterval = null;

function startLyricsSync() {

    clearInterval(lyricsInterval);

    lyricsInterval = setInterval(() => {

        if (!player) return;

        const currentTime = player.getCurrentTime();

        updateSyncedLyrics(currentTime);

    }, 200);
}

function updateSyncedLyrics(currentTime) {

    const song = songs[currentSong];

    if (!song.syncedLyrics) return;

    let currentLine = -1;

    for (let i = 0; i < song.syncedLyrics.length; i++) {

        if (currentTime >= song.syncedLyrics[i].time) {
            currentLine = i;
        }
    }

    const lyricsText =
        document.getElementById("lyricsText");

    if (!lyricsText || currentLine === -1) return;


    lyricsText.innerHTML = song.syncedLyrics
        .map((line, index) => {

            let clase = "";

            if (index === currentLine) {

                clase = "active-lyric";

                if (line.Highlight === true) {
                    clase += " highlight-lyric";
                }

                if (line.HighlightYellow === true) {
                    clase += " yellow-lyric";
                }

                if (line.HighlightBlue === true) {
                    clase += " blue-lyric";
                }
                
                if (line.HighlightGreen === true) {
                    clase += " green-lyric";
                }
                
                if (line.HighlightPurple === true) {
                    clase += " purple-lyric";
                }
                if (line.HighlightRed === true) {
                    clase += " red-lyric";
                }
            }

            return `<p class="${clase}">${line.text}</p>`;

        })
        .join("");


    // DESPLAZAMIENTO AUTOMÁTICO

    const active =
        lyricsText.querySelector(".active-lyric");

    if (active) {

        const panel =
            document.querySelector(".lyrics-panel");

        if (panel) {

            const posicion =
                active.offsetTop -
                (panel.clientHeight / 2) +
                (active.offsetHeight / 2);

            panel.scrollTo({
                top: posicion,
                behavior: "smooth"
            });
        }
    }
}
