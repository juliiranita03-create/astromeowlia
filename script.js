let currentSong = 0;
let player;
let isPlaying = false;


// CREAR REPRODUCTOR DE YOUTUBE

function iniciarReproductor() {

    player = new YT.Player("player", {

        videoId: songs[currentSong].videoId,

        playerVars: {
            autoplay: 0,
            controls: 0
        },

        events: {
            onReady: function () {
                player.setVolume(70);
                mostrarCancion();
            },

            onStateChange: function (event) {

                if (event.data === YT.PlayerState.PLAYING) {

                    isPlaying = true;

                    document.querySelector(".play-button").textContent = "❚❚";

                    document.querySelector(".cover").classList.add("playing");

                }

                if (event.data === YT.PlayerState.PAUSED) {

                    isPlaying = false;

                    document.querySelector(".play-button").textContent = "▶";

                    document.querySelector(".cover").classList.remove("playing");

                }

                if (event.data === YT.PlayerState.ENDED) {

                    siguiente();

                }
            }
        }
    });
}


// REPRODUCIR / PAUSAR

function playPause() {

    if (!player) return;

    if (isPlaying) {
        player.pauseVideo();
        clearInterval(lyricsInterval);
    } else {
        player.playVideo();
        startLyricsSync();
    }
}


// SIGUIENTE

function siguiente() {

    currentSong++;

    if (currentSong >= songs.length) {
        currentSong = 0;
    }

    cargarCancion();
}


// ANTERIOR

function anterior() {

    currentSong--;

    if (currentSong < 0) {
        currentSong = songs.length - 1;
    }

    cargarCancion();
}


// BOTONES

function nextSong() {
    siguiente();
}

function previousSong() {
    anterior();
}


// CARGAR CANCIÓN

function cargarCancion() {

    const song = songs[currentSong];

    player.loadVideoById(song.videoId);

    mostrarCancion();
}


// MOSTRAR INFORMACIÓN

function mostrarCancion() {

    const song = songs[currentSong];

    document.getElementById("songTitle").textContent =
        song.title;

    document.getElementById("artist").textContent =
        song.artist;

    document.getElementById("coverImage").src =
    song.cover;

    document.getElementById("lyricsTitle").textContent =
        song.title;

    document.getElementById("lyricsArtist").textContent =
        song.artist;

    document.getElementById("lyricsText").innerHTML =
        song.lyrics;

    mostrarPlaylist();
}


// CREAR PLAYLIST

function mostrarPlaylist() {

    const playlist =
        document.getElementById("playlist");

    playlist.innerHTML = "";

    songs.forEach(function (song, index) {

        const item =
            document.createElement("div");

        item.className = "playlist-song";

        if (index === currentSong) {
            item.classList.add("active");
        }

        item.innerHTML = `

            <img
                src="https://i.ytimg.com/vi/${song.videoId}/default.jpg"
            >

            <div class="playlist-info">

                <strong>${song.title}</strong>

                <span>${song.artist}</span>

            </div>

        `;

        item.onclick = function () {

            currentSong = index;

            cargarCancion();

        };

        playlist.appendChild(item);

    });
}


// VOLUMEN

function changeVolume() {

    if (!player) return;

    const volume =
        document.getElementById("volume").value;

    player.setVolume(volume);
}


