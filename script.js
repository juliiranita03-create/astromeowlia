// CONVERTIR TIEMPO

function convertirTiempo(segundos) {

    const minutos =
        Math.floor(segundos / 60);

    const segundosRestantes =
        Math.floor(segundos % 60);

    return minutos + ":" +
        segundosRestantes
            .toString()
            .padStart(2, "0");
}


